    static func source(prompt: String, choices: [String], correctIndex: Int, explanation: String)
        -> (topicID: String, question: CourseQuestion)? {
        if let source = CourseQuestionIndex.source(prompt: prompt, choices: choices,
                                                   correctIndex: correctIndex, explanation: explanation) { return source }
        for topic in topics {
            if let index = topic.sourcePrompts.firstIndex(of: prompt) {
                return (topic.id, CourseQuestion(id: "\(topic.id).source\(index + 1)", prompt: prompt,
                                                choices: choices, correctIndex: correctIndex, explanation: explanation))
            }
        }
        return nil
    }

